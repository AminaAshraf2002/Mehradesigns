export function translateProductTitle(
  englishTitle: string,
  lang: Language,
  productId?: string
): string {
  if (!englishTitle) return '';
  if (lang === 'en') return englishTitle;

  if (productId && curatedProductTitles[productId]) {
    return curatedProductTitles[productId];
  }

  let translated = englishTitle;
  for (const [pattern, arabicReplacement] of FASHION_KEYWORD_RULES) {
    translated = translated.replace(pattern, arabicReplacement);
  }

  return translated;
}

